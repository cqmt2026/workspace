import sqlite3
conn = sqlite3.connect('F:/market_data.db')
c = conn.cursor()
c.execute("SELECT name FROM sqlite_master WHERE type='table' AND name LIKE '%zt%'")
print('zt tables:', c.fetchall())
c.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='daily_zt'")
print('daily_zt exists:', c.fetchall())
c.execute("SELECT MAX(trade_date), COUNT(*) FROM daily_zt")
print('daily_zt max:', c.fetchall())
c.execute("SELECT trade_date, COUNT(*) FROM daily_zt GROUP BY trade_date ORDER BY trade_date DESC LIMIT 5")
print('recent dates:', c.fetchall())
conn.close()
